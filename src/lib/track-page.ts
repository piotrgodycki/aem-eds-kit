/**
 * `eds track page`: make every part of an EDS page identifiable and report it
 * to one or more data layers.
 *
 * Written into the project's `scripts/`:
 *  - `data-layers.js`  - `trackEvent(event)` pushes to every configured layer
 *    (GTM `dataLayer`, Adobe Client Data Layer `adobeDataLayer`, custom names).
 *  - `page-meta.js`    - the page's metadata, pushed first, before GTM loads.
 *  - `components.js`   - ids for the header, footer, sections and blocks, and
 *    `component_view` / `component_click` events.
 * `analytics.js` (from `eds integrate gtm`) is pointed at `data-layers.js`, and
 * `delayed.js` starts it all after LCP (page meta first, then GTM, then the
 * components), so nothing here slows the page down.
 */

export const DEFAULT_LAYERS = ["dataLayer"];
const LAYER_NAME = /^[A-Za-z_$][\w$]*$/;
export const PAGE_MARKER = "// eds track page";

export function validLayers(names: string[]): string[] {
	const out = [...new Set(names.map((n) => n.trim()).filter(Boolean))];
	for (const n of out)
		if (!LAYER_NAME.test(n))
			throw new Error(`"${n}" isn't a valid data layer name (a JS identifier).`);
	return out.length ? out : DEFAULT_LAYERS;
}

export function dataLayersJs(layers: string[]): string {
	return `// scripts/data-layers.js - generated by \`eds track page\`.
// Every event goes to each data layer listed here: GTM / GA4 read \`dataLayer\`,
// Adobe Launch / Analytics read \`adobeDataLayer\` (Adobe Client Data Layer), and
// any other name is a custom layer. Re-run \`eds track page --layer …\` to change.
export const LAYERS = ${JSON.stringify(layers)};

LAYERS.forEach((name) => {
  window[name] = window[name] || [];
});

function isDev() {
  const h = window.location.hostname;
  return h === 'localhost' || h === '127.0.0.1' || h.endsWith('.aem.page') || h.endsWith('.hlx.page');
}

export function trackEvent(event) {
  if (isDev()) {
    // eslint-disable-next-line no-console
    console.log('[data layer]', event);
  }
  // Each layer gets its own copy: a tag manager may mutate what it receives.
  LAYERS.forEach((name) => window[name].push(JSON.parse(JSON.stringify(event))));
}
`;
}

export const PAGE_META_JS = `// scripts/page-meta.js - generated by \`eds track page\`. Pushed first, before
// GTM loads, so every tag sees the page's context. Add the fields your tags need.
import { trackEvent } from './data-layers.js';

function meta(name) {
  const el = document.querySelector(\`meta[name="\${name}"]\`);
  return el ? el.content : '';
}

function environment() {
  const h = window.location.hostname;
  if (h === 'localhost' || h === '127.0.0.1') return 'dev';
  if (h.endsWith('.aem.page') || h.endsWith('.hlx.page')) return 'preview';
  if (h.endsWith('.aem.live') || h.endsWith('.hlx.live')) return 'live';
  return 'production';
}

export default async function pageMetaPush() {
  const pageMeta = {
    event: 'page_meta',
    page: {
      path: window.location.pathname,
      title: document.title,
      template: meta('template'),
      theme: meta('theme'),
      language: document.documentElement.lang || '',
      environment: environment(),
      referrer: document.referrer,
    },
  };
  trackEvent(pageMeta);
  return pageMeta;
}
`;

export const COMPONENTS_JS = `// scripts/components.js - generated by \`eds track page\`.
// Gives every part of the page a stable identity and reports it:
//   <header>, <footer>          data-component-id="header" / "footer"
//   main > .section             data-component-id="section-2"
//   .block                      data-component-id="hero-1" (name + count)
// with data-component-type, -name and -position, then pushes
//   component_view   the first time at least half of it is on screen
//   component_click  a click on a link or button inside it
import { trackEvent } from './data-layers.js';

const counts = {};

function describe(el) {
  return {
    id: el.dataset.componentId,
    type: el.dataset.componentType,
    name: el.dataset.componentName,
    position: Number(el.dataset.componentPosition),
  };
}

function tag(el, type, name, id) {
  if (el.dataset.componentId) return false;
  el.dataset.componentId = id;
  el.dataset.componentType = type;
  el.dataset.componentName = name;
  return true;
}

// Position = order on the page (top to bottom), renumbered when parts appear.
function number(root) {
  root.querySelectorAll('[data-component-id]').forEach((el, i) => {
    el.dataset.componentPosition = String(i + 1);
  });
}

const seen = new IntersectionObserver((entries) => {
  entries.forEach((entry) => {
    if (!entry.isIntersecting) return;
    seen.unobserve(entry.target);
    trackEvent({ event: 'component_view', component: describe(entry.target) });
  });
}, { threshold: 0.5 });

function scan(root) {
  const found = [];
  root.querySelectorAll('header, footer').forEach((el) => {
    const type = el.tagName.toLowerCase();
    if (tag(el, type, type, type)) found.push(el);
  });
  root.querySelectorAll('main > .section').forEach((el, i) => {
    if (tag(el, 'section', 'section', \`section-\${i + 1}\`)) found.push(el);
  });
  root.querySelectorAll('.block[data-block-name]').forEach((el) => {
    const name = el.dataset.blockName;
    if (el.dataset.componentId) return;
    counts[name] = (counts[name] || 0) + 1;
    if (tag(el, 'block', name, \`\${name}-\${counts[name]}\`)) found.push(el);
  });
  if (found.length) number(root);
  found.forEach((el) => seen.observe(el));
}

export default function initComponents(doc = document) {
  scan(doc);
  // Blocks that load later (fragments, the header and footer blocks).
  new MutationObserver(() => scan(doc)).observe(doc.body, { childList: true, subtree: true });

  doc.addEventListener('click', (e) => {
    const target = e.target.closest('a, button');
    const component = target && target.closest('[data-component-id]');
    if (!component) return;
    trackEvent({
      event: 'component_click',
      component: describe(component),
      link: {
        text: (target.textContent || '').trim().slice(0, 100),
        url: target.href || '',
      },
    });
  }, { capture: true });
}
`;

/** The delayed-phase start: page meta first, then GTM (when present), then the components. */
export function delayedSnippet(hasGtm: boolean): string {
	return `${PAGE_MARKER}: page meta first, ${hasGtm ? "then GTM, " : ""}then every component.
import pageMetaPush from './page-meta.js';
import initComponents from './components.js';
${hasGtm ? "import { loadGTM } from './analytics.js';\n" : ""}
pageMetaPush()${hasGtm ? ".then(loadGTM)" : ""}.then(() => initComponents(document));
`;
}

/**
 * Point `analytics.js` (from \`eds integrate gtm\`) at the shared data layers, so
 * existing \`trackEvent\` calls (\`eds track block\`) reach every layer too.
 */
export function patchAnalytics(js: string): { js: string; changed: boolean } {
	if (js.includes("from './data-layers.js'")) return { js, changed: false };
	const own = /export function trackEvent\(event\) \{[\s\S]*?\n\}\n/;
	if (!own.test(js)) return { js, changed: false };
	const out = js.replace(own, "export { trackEvent } from './data-layers.js';\n");
	return { js: out, changed: true };
}

/** Remove the GTM integration's own page-meta start, so page meta isn't pushed twice. */
export function stripGtmStart(delayed: string): string {
	return delayed
		.replace(/^import pageMetaPush from '\.\/page-meta\.js';\n/m, "")
		.replace(/^const pageMetaReady = pageMetaPush\(\);\npageMetaReady\.then\(loadGTM\);\n?/m, "")
		.replace(/^import \{ loadGTM \} from '\.\/analytics\.js';\n/m, "");
}
